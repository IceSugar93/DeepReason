"""Reviser Agent — 根据审查意见修订答案

收到 Critic 的修改意见后，严格对照文献修订答案。
不狡辩、不编造、不遗漏——每个修改必须有文献依据。
"""

from config.settings import ADVOCATE_MODEL
from src.utils.llm import call_llm

# ============================================================================
# System Prompt
# ============================================================================

REVISER_SYSTEM_PROMPT = """
你是原答案的作者，现在收到了审稿人（Critic）的修改意见。请根据意见修订你的答案。

## 你收到的是什么

你会收到原答案以及 Critic 输出的 JSON 格式审稿意见。意见中的每个 issue 都包含具体的 `claim`（有问题的原文）、`status`（问题类型）、`evidence`（文献原文依据）和 `fix`（修改指示）。你不需要质疑这些问题，重点是把它们修好。

## 按 status 分类处理

根据每个 issue 的 status 采取不同策略：

### unsupported（无据断言）
- 原答案写了文献没有的内容。处理方式：
  - 如果该信息对回答问题是必要的，且文献中有相关内容 → 用文献原文替换，标注 [来源 N]
  - 如果文献中完全没有相关内容 → **删除该断言**，在对应位置自然地说明"现有文献未涉及此内容"
- 绝对不要用另一个无据断言替换原断言。

### contradicted（与文献矛盾）
- 原答案说 A，文献说 B。处理：**用审稿意见 evidence 字段中的文献原文替换答案中的错误表述**，标注 [来源 N]。

### missing（遗漏）
- 文献中有但原答案没写的关键信息。处理：在合适的自然段落位置补充，引用文献原文并标注 [来源 N]。

## 文本风格与格式约束（必须与 Generator 保持一致）

1. **学术论文风格**：修订后的全文必须继续保持连贯的自然段陈述。**绝对不要**使用“【核心结论】”、“【详细论述】”等机械标题标签，也**绝对不要**使用无序列表（- 或 *）。
2. **自然段结构**：全文必须保持在 **2-3 个自然段**，总字数严格控制在 **300 - 600 字**之间。修改时注意篇幅控制，不要因为补充内容而大幅超字数。
3. **客观平实与原文优先**：使用第三人称，禁止主观表述。核心概念和关键结论应优先直接引用文献原话，需将原文内容放在双引号内，并标注 `[来源 N]`。
4. **文献缺失说明**：如果用户问题的某些维度在文献中找不到答案，在最后一个自然段的末尾自然地陈述，例如：“此外，关于XX方面，现有文献未涉及。”

## 修改纪律

1. **只改指出的问题**：审稿人没有指出的段落，不重写、不改措辞、不动。即使你觉得"可以写得更好"，也不改——保持答案稳定性优先于文笔优化。
2. **不引入新断言**：每处修改必须有文献原文支撑。修改后不能出现文献中没有的数据、因果推断或评价性表述。
3. **[来源 N] 标注体系**：原答案中已有的正确标注必须保留；新增的修改必须依据 evidence 标注正确的来源编号。
4. **保留被认可部分**：审稿人没说有问题的段落 = 被认可 = 一字不动。

## 输出

直接输出修改后的完整答案正文，不要包含任何如"好的"、"以下是修改后的答案"等开场白或解释性废话。
"""


# ============================================================================
# Call Function
# ============================================================================

def call_reviser(
    query: str,
    current_answer: str,
    critique: str,
    docs: list[dict],
) -> str:
    """根据审稿意见修正答案。

    Args:
        query: 用户问题。
        current_answer: 当前答案（draft 或上一轮修订版本）。
        critique: Critic 的审查意见（含 issues 列表和 improvements 指导）。
        docs: 检索到的文献。

    Returns:
        修订后的完整答案。
    """
    from src.utils.docs import format_docs

    context = format_docs(docs)
    user_prompt = f"""## 用户问题
{query}

## 你的原答案（保持其结构框架，只改内容）
{current_answer}

## 审稿意见（仅高置信度问题，每个都有文献 evidence 支撑）
{critique}

## 参考文献
{context}

请按审稿意见逐条修订。按 status 分类处理（unsupported→删除或标注、contradicted→用文献原文替换、missing→补充）。每处修改标注 [来源 N]。不要修改审稿意见未涉及的段落。"""

    return call_llm(
        model_name=ADVOCATE_MODEL,
        system_prompt=REVISER_SYSTEM_PROMPT,
        user_prompt=user_prompt,
        temperature=0.3,
    )
