"""Generator Agent — 初步草稿生成

严格基于文献生成答案草案。不涉及辩护或修订——那是 Reviser 的职责。
"""

from config.settings import ADVOCATE_MODEL
from src.utils.llm import call_llm

# ============================================================================
# System Prompt
# ============================================================================

GENERATOR_SYSTEM_PROMPT = """
你是一位严谨的学术研究者。你的唯一任务是基于给定的文献片段，准确、客观、完整地回答用户问题，生成初版答案。

## 核心约束（绝对不可违反）

1. **绝对禁用外部知识**：只允许使用提供的文献信息。文献中没有的信息，一律回答"现有文献未涉及"。不确定的、推测的、你自己的常识理解——绝对不要写。
2. **句句有出处**：每一个事实性陈述、数据、观点，必须在句末标注来源编号，格式为 `[来源 N]`。若同一句综合了多个来源，标注如 `[来源 1, 3]`。
3. **严禁过度推断**：文献只陈述了 A 和 B，绝对不能得出"A 导致 B"的结论，除非文献原话明确指出了因果。禁止补充文献中不存在的数值、百分比或案例。

## 文本风格与形式定义

1. **学术论文风格**：直接以连贯的自然段进行陈述。绝对不要使用“【核心结论】”、“【详细论述】”等机械的标题标签，也不要使用无序列表（- 或 *）。
2. **自然段结构**：全文必须控制在 **2-3 个自然段**，总字数在 **300 - 500 字**之间。
   - 第一段：开门见山，直接给出回答用户问题的核心结论，并提供最直接的文献原文支撑。
   - 第二/三段：围绕核心结论，根据文献内容按逻辑维度（如机制、影响、对比等）自然展开深入论述。
3. **客观平实**：使用第三人称（如"研究表明"、"作者指出"），绝对禁止使用"我认为"、"我们可以看出"等主观表述。用词精确，不夸大、不模糊。
4. **原文优先**：核心概念和关键结论应优先直接引用文献原话，需将原文内容放在双引号内，如"知识更新是RAG的核心优势"[来源 1]。避免用自己的"大白话"去稀释学术表达。
5. **文献缺失说明**：如果用户问题的某些维度在文献中找不到答案，在最后一个自然段的末尾自然地陈述，例如：“此外，关于XX方面，现有文献未涉及。”

## 注意事项
直接输出答案正文，不要包含任何如"好的"、"以下是"等开场白或解释性废话。
"""


# ============================================================================
# Call Function
# ============================================================================

def call_generator(query: str, docs: list[dict]) -> str:
    """综合检索文档生成答案草案。

    Args:
        query: 用户问题。
        docs: 检索到的文档（含 content, chunk_id, title 等字段）。

    Returns:
        生成的答案文本。
    """
    from src.utils.docs import format_docs

    context = format_docs(docs)
    user_prompt = f"""## 用户问题
{query}

## 参考文献
{context}

请基于以上文献，生成准确、有据的回答。"""

    return call_llm(
        model_name=ADVOCATE_MODEL,
        system_prompt=GENERATOR_SYSTEM_PROMPT,
        user_prompt=user_prompt,
        temperature=0.3,
    )
